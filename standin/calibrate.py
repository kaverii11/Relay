"""Derive the stand-in's parameters from real Groq probe logs (probe/raw/*.jsonl).

Every parameter is written with its provenance: "measured: ..." or "assumed: ...".
Run: .venv/bin/python standin/calibrate.py  ->  standin/calibration.json
"""
import glob
import json
import math
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def rows(pattern):
    return [json.loads(l) for f in sorted(glob.glob(str(ROOT / "probe/raw" / pattern))) for l in open(f)]


def ok(rs):
    return [r for r in rs if r["status"] == 200 and r.get("ttft_ms")]


short = ok(rows("spread_short_*.jsonl"))
draft = ok(rows("spread_draft_*.jsonl"))
inflight = ok(rows("inflight_*.jsonl"))


def by_model(rs, m):
    # exact id: "gpt-oss-120b".endswith("20b") is True, which silently mixed the models
    return [r for r in rs if r["model"] == f"openai/gpt-oss-{m}"]


def uncached(rs):
    return [r for r in rs if not r.get("cached_tokens")]


cal = {"_note": "Generated by standin/calibrate.py from probe/raw. Do not hand-edit values; edit the script.",
       "models": {}}

# Input-size slope: 120b short (~314 tok) vs 120b draft (~2.8k tok), uncached medians.
s120, d120 = uncached(by_model(short, "120b")), uncached(by_model(draft, "120b"))
in_s, in_d = np.median([r["tokens_in"] for r in s120]), np.median([r["tokens_in"] for r in d120])
t_s, t_d = np.median([r["ttft_ms"] for r in s120]), np.median([r["ttft_ms"] for r in d120])
slope = max(0.0, (t_d - t_s) / (in_d - in_s))

for m in ("20b", "120b"):
    sm = uncached(by_model(short, m))
    dm = uncached(by_model(draft, m))
    allm = sm + dm
    t = np.array([r["ttft_ms"] for r in sm])
    med = float(np.median(t))
    body = t[t <= 2 * med]            # the rare-delay calls are excluded from the body fit
    # rare delay is counted over ALL calls (cached or not): a slow call is slow either way
    t_all = np.array([r["ttft_ms"] for r in by_model(short, m)])
    outl = t_all[t_all > 2 * np.median(t_all)]
    sigma = float(np.std(np.log(body / med)))
    base = med - slope * float(np.median([r["tokens_in"] for r in sm]))
    gap = [r["ttft_ms"] - r["first_any_ms"] for r in allm if r.get("first_any_ms")]
    dec = [(r["tokens_out"] - r["reasoning_tokens"]) / ((r["total_ms"] - r["ttft_ms"]) / 1000)
           for r in allm if r["total_ms"] - r["ttft_ms"] > 50]
    cal["models"][f"openai/gpt-oss-{m}"] = {
        "ttft_base_ms": {"value": round(base, 1),
                         "source": f"measured: median uncached first-answer-token of {len(sm)} short calls minus slope x median input"},
        "ttft_ms_per_input_token": {"value": round(slope, 4),
                                    "source": f"measured: (120b draft median {t_d:.0f} - short median {t_s:.0f}) / ({in_d:.0f} - {in_s:.0f} tokens); same slope assumed for 20b"},
        "ttft_lognormal_sigma": {"value": round(sigma, 3),
                                 "source": f"measured: std of log(ttft/median) over {len(body)} non-outlier uncached short calls"},
        "reasoning_gap_ms": {"value": round(float(np.median(gap)), 1),
                             "source": f"measured: median (first answer token - first any token), n={len(gap)}"},
        "decode_tok_per_s": {"value": round(float(np.median(dec)), 0) if dec else None,
                             "source": f"measured: median answer tokens/s, n={len(dec)}" + (" (UNCERTAIN, small n)" if len(dec) < 10 else "")},
        "rare_delay_observed": {"value": f"{len(outl)}/{len(t_all)}",
                                "source": "measured: short calls (cached or not) with ttft > 2x that model's median"},
    }

# Rare pre-first-token delay: multiplier from all observed outliers (both models, cached or not).
outs, n = [], 0
for m in ("20b", "120b"):
    t = np.array([r["ttft_ms"] for r in by_model(short, m)])
    n += len(t)
    outs += list(t[t > 2 * np.median(t)] / np.median(t))
k = len(outs)
z = 1.96
p = k / n
w_c = (p + z * z / (2 * n)) / (1 + z * z / n)
w_h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
cal["rare_delay"] = {
    "multiplier": {"value": round(float(np.mean(outs)), 2) if outs else 2.4,
                   "source": f"measured: mean outlier/median over {len(outs)} outliers"},
    "rate_default": {"value": 0.05, "source": "assumed: point estimate ~2/40; scenarios also run 0.02 and 0.10"},
    "rate_95ci": {"value": [round(w_c - w_h, 3), round(w_c + w_h, 3)],
                  "source": f"measured: Wilson 95% interval for {k}/{n} short calls (both models)"},
}

# Load slowdown from the in-flight test (tiny prompts, Qwen). k=1 is a single sample, so k=4 is the baseline.
med_k = {}
for r in inflight:
    med_k.setdefault(int(r["tag"].split("_")[1]), []).append(r["ttft_ms"])
med_k = {kk: float(np.median(v)) for kk, v in sorted(med_k.items())}
ks = [kk for kk in med_k if kk >= 4]
a = float(np.polyfit([kk - 4 for kk in ks], [med_k[kk] / med_k[4] - 1 for kk in ks], 1)[0]) if len(ks) >= 2 else 0.02
cal["load_slowdown"] = {
    "per_inflight_fraction": {"value": round(max(a, 0.0), 4),
                              "source": f"measured up to 16 in flight on qwen (medians by k: {med_k}); linear fit vs k=4. "
                                        "ASSUMED to continue linearly beyond 16 - biggest difference from the real thing"},
    "max_concurrency": {"value": 64, "source": "assumed: server-side FIFO above this; never observed on Groq"},
}

cal["limits"] = {
    "rpm": {"value": 30, "source": "measured: 30 OK then 429 'RPM: Limit 30' (qwen)"},
    "itpm": {"value": 7000, "source": "measured: 429 'ITPM: Limit 7000' (qwen)"},
    "tpm": {"value": 8000, "source": "measured: header x-ratelimit-limit-tokens on all 3 models"},
    "rpd": {"value": 1000, "source": "measured: header x-ratelimit-limit-requests on all 3 models"},
    "tpd": {"value": 200000, "source": "docs only (console.groq.com/docs/rate-limits); never hit"},
    "refill": {"value": "continuous, L/window per second",
               "source": "measured: ITPM retry wait matched (used+req-limit)/(limit/60) to 6 decimals; RPM recovery ~2 s; "
                         "RPD reset-requests 86.4 s per request. TPD refill ASSUMED the same (not measured)"},
    "otpm": {"value": None, "source": "not measured, so not modelled"},
}
cal["failures"] = {
    "error_5xx_rate": {"value": 0.01, "source": "assumed: 0 errors in 137 real calls (95% upper bound ~2.2% by rule of three)"},
    "midstream_stall_rate": {"value": 0.01, "source": "assumed: never observed; 'succeeds slowly' case from the brief"},
    "midstream_stall_ms": {"value": 4000, "source": "assumed"},
    "midstream_drop_rate": {"value": 0.005, "source": "assumed: never observed"},
}
cal["prompt_cache"] = {"value": "not modelled",
                       "source": "decision DECISIONS §16: fitted on uncached calls; Groq's cache hit rate under load unknown"}

out = ROOT / "standin/calibration.json"
out.write_text(json.dumps(cal, indent=2))
print(json.dumps(cal, indent=2))
