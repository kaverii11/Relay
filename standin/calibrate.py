"""Derive the stand-in's parameters from real Groq probe logs (probe/raw/*.jsonl).

Every parameter is written with its provenance: "measured: ..." or "assumed: ...".
Run: .venv/bin/python standin/calibrate.py  ->  standin/calibration.json
"""
import glob
import json
import math
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def rows(pattern):
    """Every record of the probe logs matching a file pattern."""
    return [json.loads(l) for f in sorted(glob.glob(str(ROOT / "probe/raw" / pattern))) for l in open(f)]


def ok(rs):
    """Only successful calls that produced a first token."""
    return [r for r in rs if r["status"] == 200 and r.get("ttft_ms")]


# Two MEASURED latency profiles (K §25), each fitted only from its own probe run; never pooled.
PROFILES = {
    "afternoon": {"files": ["spread_short_20261109_161924.jsonl", "spread_short_20261109_162231.jsonl",
                            "spread_draft_20261109_162318.jsonl"], "label": "stage 2a, 2026-11-09 16:19 IST"},
    "evening": {"files": ["spread_short_20261109_220024.jsonl", "spread_draft_20261109_220214.jsonl"],
                "label": "stage 2b, 2026-11-09 22:00 IST"},
}
inflight = ok(rows("inflight_*.jsonl"))


def load(files):
    """Short and draft-sized calls from a set of spread-phase files."""
    rs = ok([json.loads(l) for f in files for l in open(ROOT / "probe/raw" / f)])
    return [r for r in rs if r["tag"] == "spread_short"], [r for r in rs if r["tag"] == "spread_draft"]


def by_model(rs, m):
    # exact id: "gpt-oss-120b".endswith("20b") is True, which silently mixed the models
    """Calls of one model (exact id match)."""
    return [r for r in rs if r["model"] == f"openai/gpt-oss-{m}"]


def uncached(rs):
    """Calls with no prompt-cache hit (a cache hit halves first-token time)."""
    return [r for r in rs if not r.get("cached_tokens")]


def med(rs, k="ttft_ms"):
    """Median of a field."""
    return float(np.median([r[k] for r in rs]))


def wilson(k, n, z=1.96):
    """95 % Wilson interval for k of n (e.g. the slow-call rate)."""
    p = k / n
    c = (p + z * z / (2 * n)) / (1 + z * z / n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return [round(c - h, 3), round(c + h, 3)]


cal = {"_note": "Generated by standin/calibrate.py from probe/raw. Do not hand-edit values; edit the script.",
       "profiles": {}}

A_short, A_draft = load(PROFILES["afternoon"]["files"])
# Input-size slope: 120b short (~314 tok) vs 120b draft (~2.8k tok), uncached medians. Afternoon only
# (the evening run has no 120b short calls); used by both profiles.
s120, d120 = uncached(by_model(A_short, "120b")), uncached(by_model(A_draft, "120b"))
in_s, in_d = med(s120, "tokens_in"), med(d120, "tokens_in")
t_s, t_d = med(s120), med(d120)
slope = max(0.0, (t_d - t_s) / (in_d - in_s))
cal["ttft_ms_per_input_token"] = {"value": round(slope, 4), "source":
    f"measured (afternoon): (120b draft median {t_d:.0f} - short median {t_s:.0f}) / ({in_d:.0f} - {in_s:.0f} tokens); "
    "same slope assumed for 20b and for the evening profile"}
# Slow-call threshold: 2x the AFTERNOON median of that model's calls of that kind, in BOTH profiles,
# so "slow" means the same thing in each (in the evening 45% are slow, so the evening's own median
# sits between the two clusters and can't serve as a reference).
REF = {(m, kind): med(uncached(by_model(rs, m))) for m in ("20b", "120b")
       for kind, rs in (("short", A_short), ("draft", A_draft)) if uncached(by_model(rs, m))}

for pname, pdef in PROFILES.items():
    short, draft = load(pdef["files"])
    prof = {"label": pdef["label"], "models": {}}
    mults, n_slow, n_all = [], 0, 0
    for m in ("20b", "120b"):
        # body = calls at or under 2x the afternoon reference; fit on uncached ones
        kind, src = ("short", short) if by_model(short, m) else ("draft", draft)
        thr = 2 * REF[(m, kind)]
        allc = by_model(src, m)
        body = [r for r in uncached(allc) if r["ttft_ms"] <= thr]
        slow = [r for r in allc if r["ttft_ms"] > thr]          # cached or not: a slow call is slow either way
        bmed = med(body)
        t = np.array([r["ttft_ms"] for r in body])
        n_body = len(body)
        sig_src = f"measured ({pname}): std of log(ttft/median) over {n_body} non-slow uncached {kind} calls"
        sigma = float(np.std(np.log(t / bmed)))
        if n_body < 5:                                         # too few to estimate a spread
            sigma = prof_af["models"][f"openai/gpt-oss-{m}"]["ttft_lognormal_sigma"]["value"]
            sig_src = f"from afternoon: only {n_body} {pname} calls, too few to fit a spread"
        base = bmed - slope * med(body, "tokens_in")
        both = uncached(by_model(short, m) + by_model(draft, m))
        gap = [r["ttft_ms"] - r["first_any_ms"] for r in both if r.get("first_any_ms")]
        dec = [(r["tokens_out"] - r["reasoning_tokens"]) / ((r["total_ms"] - r["ttft_ms"]) / 1000)
               for r in both if r["total_ms"] - r["ttft_ms"] > 50]
        dec_v = round(float(np.median(dec)), 0) if dec else None
        dec_src = f"measured ({pname}): median answer tokens/s, uncached, n={len(dec)}" + (" (UNCERTAIN, small n)" if len(dec) < 10 else "")
        if len(dec) < 3 and pname != "afternoon":
            dec_v = prof_af["models"][f"openai/gpt-oss-{m}"]["decode_tok_per_s"]["value"]
            dec_src = f"from afternoon: only {len(dec)} {pname} call(s) streamed long enough to measure"
        if m == "20b":                                       # rate + multipliers from 20b short calls (the only model with short calls in both runs)
            n_slow += len(slow)
            n_all += len(allc)
            mults += [r["ttft_ms"] / bmed for r in slow]
        prof["models"][f"openai/gpt-oss-{m}"] = {
            "ttft_base_ms": {"value": round(base, 1), "source":
                f"measured ({pname}): median uncached first-answer-token of {n_body} non-slow {kind} calls minus slope x median input"},
            "ttft_lognormal_sigma": {"value": round(sigma, 3), "source": sig_src},
            "reasoning_gap_ms": {"value": round(float(np.median(gap)), 1),
                                 "source": f"measured ({pname}): median (first answer token - first any token), uncached, n={len(gap)}"},
            "decode_tok_per_s": {"value": dec_v, "source": dec_src},
            "slow_observed": {"value": f"{len(slow)}/{len(allc)} {kind} calls > {thr:.0f} ms",
                              "source": "measured: threshold = 2x the afternoon median for this model and call kind"},
        }
    prof["rare_delay"] = {
        "rate": {"value": round(n_slow / n_all, 3), "source":
            f"measured ({pname}): X"},
        "rate_95ci": {"value": wilson(n_slow, n_all), "source": f"Wilson 95% interval for {n_slow}/{n_all}"},
        "multipliers": {"value": [round(x, 2) for x in sorted(mults)], "source":
            f"measured ({pname}): each slow call's ttft / its profile's non-slow median; the stand-in draws one at random"},
        "n": {"value": n_all, "source": f"20b short calls in {pdef['label']}"},
    }
    cal["profiles"][pname] = prof
    if pname == "afternoon":
        prof_af = prof
cal["profiles"]["evening"]["label"] += " (n=20 short calls on 20b, n=3 drafts on 120b; thin)"
cal["default_profile"] = "afternoon"

# Load slowdown from the in-flight test (tiny prompts, Qwen). k=1 is a single sample, so k=4 is the baseline.
med_k = {}
for r in inflight:
    med_k.setdefault(int(r["tag"].split("_")[1]), []).append(r["ttft_ms"])
med_k = {kk: float(np.median(v)) for kk, v in sorted(med_k.items())}
ks = [kk for kk in med_k if kk >= 4]
a = float(np.polyfit([kk - 4 for kk in ks], [med_k[kk] / med_k[4] - 1 for kk in ks], 1)[0]) if len(ks) >= 2 else 0.02
cal["load_slowdown"] = {
    "per_inflight_fraction": {"value": round(max(a, 0.0), 4),
                              "source": f"measured up to 16 in flight on qwen (medians by k: {med_k}); linear fit vs k=4. "
                                        "ASSUMED to continue linearly beyond 16 - biggest difference from the real thing"},
    "max_concurrency": {"value": 64, "source": "assumed: server-side FIFO above this; never observed on Groq"},
}

cal["limits"] = {
    "rpm": {"value": 30, "source": "measured: 30 OK then 429 'RPM: Limit 30' (qwen)"},
    "itpm": {"value": 7000, "source": "measured: 429 'ITPM: Limit 7000' (qwen)"},
    "tpm": {"value": 8000, "source": "measured: header x-ratelimit-limit-tokens on all 3 models"},
    "rpd": {"value": 1000, "source": "measured: header x-ratelimit-limit-requests on all 3 models"},
    "tpd": {"value": 200000, "source": "docs only (console.groq.com/docs/rate-limits); never hit"},
    "refill": {"value": "continuous, L/window per second",
               "source": "measured: ITPM retry wait matched (used+req-limit)/(limit/60) to 6 decimals; RPM recovery ~2 s; "
                         "RPD reset-requests 86.4 s per request. TPD refill ASSUMED the same (not measured)"},
    "otpm": {"value": None, "source": "not measured, so not modelled"},
}
cal["failures"] = {
    "error_5xx_rate": {"value": 0.01, "source": "assumed: 0 errors in 137 real calls (95% upper bound ~2.2% by rule of three)"},
    "midstream_stall_rate": {"value": 0.01, "source": "assumed: never observed; 'succeeds slowly' case from the brief"},
    "midstream_stall_ms": {"value": 4000, "source": "assumed"},
    "midstream_drop_rate": {"value": 0.005, "source": "assumed: never observed"},
}
cal["prompt_cache"] = {"value": "not modelled",
                       "source": "decision DECISIONS §16: fitted on uncached calls; Groq's cache hit rate under load unknown"}

out = ROOT / "standin/calibration.json"
out.write_text(json.dumps(cal, indent=2))
print(json.dumps(cal, indent=2))
